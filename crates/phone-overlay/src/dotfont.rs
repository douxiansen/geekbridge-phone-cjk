/// The glyph rows for `c`, if the font has it.
pub fn glyph(c: char) -> Option<&'static [&'static str; ROWS]> {
    let up = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(k, _)| *k == up).map(|(_, g)| g)
}

/// Whether every character of `s` has a glyph.
pub fn supported(s: &str) -> bool {
    s.chars().all(|c| glyph(c).is_some())
}

/// Columns `s` occupies, with a one-column gap between glyphs. Characters the
/// font lacks count as blank.
pub fn columns(s: &str) -> usize {
    let mut n = 0;
    let mut first = true;
    for c in s.chars() {
        if !first {
            n += 1;
        }
        first = false;
        n += glyph(c).map_or(3, |g| g[0].len());
    }
    n
}

/// Every lit dot of `s` as `(column, row)`, glyph gaps included. Unknown
/// characters are skipped as blanks.
pub fn lit_dots(s: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let mut x0 = 0;
    for c in s.chars() {
        let w = match glyph(c) {
            Some(g) => {
                for (row, line) in g.iter().enumerate() {
                    for (col, b) in line.bytes().enumerate() {
                        if b == b'1' {
                            out.push((x0 + col, row));
                        }
                    }
                }
                g[0].len()
            }
            None => 3,
        };
        x0 += w + 1;
    }
    out
}

/// Every grid cell of `s` as `(column, row, lit)`, glyph gaps excluded, for
/// drawing the faint unlit grid behind the lit dots.
pub fn cells(s: &str) -> Vec<(usize, usize, bool)> {
    let mut out = Vec::new();
    let mut x0 = 0;
    for c in s.chars() {
        let w = match glyph(c) {
            Some(g) => {
                for (row, line) in g.iter().enumerate() {
                    for (col, b) in line.bytes().enumerate() {
                        out.push((x0 + col, row, b == b'1'));
                    }
                }
                g[0].len()
            }
            None => 3,
        };
        x0 += w + 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_row_has_the_glyph_width() {
        for (c, g) in GLYPHS {
            let w = g[0].len();
            assert!(g.iter().all(|r| r.len() == w), "glyph {c}");
        }
    }

    #[test]
    fn columns_include_gaps() {
        assert_eq!(columns(""), 0);
        assert_eq!(columns("A"), 5);
        assert_eq!(columns("01:23"), 5 + 1 + 5 + 1 + 1 + 1 + 5 + 1 + 5);
    }

    #[test]
    fn lowercase_and_unknown() {
        assert!(glyph('g').is_some());
        assert!(!supported("é"));
        assert!(supported("Hang up"));
        assert_eq!(lit_dots("é"), vec![]);
    }

    #[test]
    fn colon_dots_are_at_the_right_rows() {
        assert_eq!(lit_dots(":"), vec![(0, 1), (0, 5)]);
    }
}
